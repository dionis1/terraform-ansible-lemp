#!/usr/bin/env python3
"""Generate local Ansible inventory from Terraform output and libvirt DHCP leases."""
import argparse
import ipaddress
import json
from pathlib import Path
import shlex
import subprocess
import time

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--ssh-key", default="~/.ssh/terraform-lemp")
parser.add_argument("--timeout", type=int, default=120)
args = parser.parse_args()
key = Path(args.ssh_key).expanduser().resolve()
if not key.is_file():
    parser.error("SSH private key does not exist; pass --ssh-key")
name = json.loads(subprocess.check_output(
    ["terraform", "-chdir=" + str(ROOT / "terraform"), "output", "-json", "vm_name"], text=True))
deadline = time.monotonic() + args.timeout
address = None
while True:
    result = subprocess.run(["virsh", "-c", "qemu:///system", "domifaddr", name,
                             "--source", "lease"], capture_output=True, text=True, check=True)
    for line in result.stdout.splitlines():
        fields = line.split()
        if len(fields) >= 4 and fields[2] == "ipv4":
            address = str(ipaddress.ip_interface(fields[3]).ip)
            break
    if address or time.monotonic() >= deadline:
        break
    time.sleep(2)
if not address:
    raise SystemExit("No IPv4 DHCP lease found for the Terraform VM before timeout")
content = ("# Generated by scripts/generate-inventory.py; ignored by Git.\n"
           "[web]\nlemp-server ansible_host=" + address + "\n\n[web:vars]\n"
           "ansible_user=devops\nansible_ssh_private_key_file=" + shlex.quote(str(key)) +
           "\nansible_python_interpreter=/usr/bin/python3\n")
output = ROOT / "ansible/inventory.ini"
tmp = output.with_suffix(".ini.tmp")
try:
    tmp.write_text(content)
    tmp.chmod(0o600)
    tmp.replace(output)
finally:
    tmp.unlink(missing_ok=True)
print("Generated local inventory for " + name + " at " + address)
